import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

TextStyle daftarNumberStyle({
  double fontSize = 28,
  FontWeight fontWeight = FontWeight.w700,
  Color? color,
}) {
  return GoogleFonts.spaceMono(
    fontSize: fontSize,
    fontWeight: fontWeight,
    color: color,
  );
}
